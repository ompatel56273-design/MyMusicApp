/**
 * Returns an accessible, standardized SVG icon string.
 */
export function getIconSvg(name: IconName, options: IconOptions = {}): string {
  const size = options.size ?? 20;
  const strokeWidth = options.strokeWidth ?? 2;
  const color = options.color ?? 'currentColor';
  const className = options.className ?? '';
  const ariaHidden = options.ariaHidden ?? (options.ariaLabel ? false : true);
  const ariaLabelAttr = options.ariaLabel ? ` aria-label="${options.ariaLabel}" role="img"` : (ariaHidden ? ' aria-hidden="true"' : '');
  const pathContent = SVG_PATHS[name] || SVG_PATHS['music'];

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" class="app-icon ${className}"${ariaLabelAttr}>${pathContent}</svg>`;
}

/**
 * Creates an SVG DOM Element directly.
 */
export function createIconElement(name: IconName, options: IconOptions = {}): SVGSVGElement | null {
  if (typeof document === 'undefined') {
    return null;
  }
  const wrapper = document.createElement('div');
  wrapper.innerHTML = getIconSvg(name, options);
  return wrapper.querySelector('svg');
}
